'use strict';
const { _electron, expect } = require('@playwright/test');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
(async () => {
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'music-tools-reference-ui-'));
  const output = path.join(data, 'lyrics'); fs.mkdirSync(output);
  const env = { ...process.env, MUSIC_TOOLS_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ executablePath: process.env.MUSIC_TOOLS_EXECUTABLE || require('electron'), args: process.env.MUSIC_TOOLS_EXECUTABLE ? [] : [root], env, timeout: 60000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const action = key => page.locator(`[data-lyric-action="${key}"]`);
  const input = page.locator('[data-lyric-reference]');
  const api = (name, ...args) => page.evaluate(({ name, args }) => window.music.invoke(name, ...args), { name, args });
  try {
    await expect(page.locator('.audio-tile')).toHaveCount(0);
    await expect(page.locator('.sidebar [data-action="extract-lyrics"]')).toBeEnabled();
    await page.locator('.sidebar [data-action="extract-lyrics"]').click();
    await expect(page.locator('#modal')).toBeVisible();
    await expect(input).toBeFocused();
    await expect(action('export')).toBeDisabled();
    assert.equal(await api('lyric-export', { audioPath: 'C:\\not-imported.mp3', directory: output, original: '[00:01]x' }).then(() => false, () => true), true);
    assert.equal(await api('lyric-export', { directory: output, original: '[00:01]x' }).then(() => false, () => true), true);
    await app.evaluate(({ app, dialog }, output) => {
      const req = process.getBuiltinModule('module').createRequire(app.getAppPath() + '/package.json');
      globalThis.referenceCalls = [];
      globalThis.fetch = async (url, options) => {
        globalThis.referenceCalls.push(String(url));
        if (String(url).includes('163cn.tv')) return new Response(null, { status: 302, headers: { Location: 'https://music.163.com/#/song?id=123' } });
        if (String(url).includes('/api/song/detail/')) return new Response(JSON.stringify({ code: 200, songs: [{ id: 123, name: '在线歌曲', artists: globalThis.referenceMinimal ? [] : [{ name: '在线歌手' }], album: globalThis.referenceMinimal ? {} : { name: '专辑' }, duration: globalThis.referenceMinimal ? undefined : 120000 }] }));
        if (String(url).includes('fcg_play_single_song')) return new Response(JSON.stringify({ code: 0, data: [{ id: 456, mid: '003OUlho2HcRHC', name: 'QQ 歌曲', singer: [{ name: 'QQ 歌手' }], album: { name: 'QQ 专辑' }, interval: 120 }] }));
        throw new Error('Unexpected metadata URL: ' + url);
      };
      const providers = req('./source/core/providers.cjs');
      providers.search = async () => ({ candidates: [{ source: 'netease', id: 'netease:123', title: '搜索歌曲', artist: '搜索歌手', duration: 120 }], errors: [] });
      providers.enrich = async (candidate, options) => {
        globalThis.referenceCalls.push(candidate.id);
        if (globalThis.referenceSlow) await new Promise((resolve, reject) => { const timer = setTimeout(resolve, 10000); options.signal.addEventListener('abort', () => { clearTimeout(timer); reject(new DOMException('Canceled', 'AbortError')); }, { once: true }); });
        return { syncedLyrics: '[00:01.00]First line\n[00:03.00]Second line', translatedLyrics: '[00:01.00]第一句\n[00:03.00]第二句', errors: [] };
      };
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [output] });
    }, output);
    await input.fill('123'); await input.press('Enter');
    await expect(page.locator('[data-lyric-error]')).toContainText('请选择 QQ 音乐或网易云音乐');
    await expect(action('export')).toBeDisabled();
    await page.locator('[data-lyric-reference-source]').selectOption('netease');
    await action('resolve').click();
    await expect(page.locator('[data-lyric-text="original"]')).toHaveValue(/First line/);
    await expect(page.locator('[data-lyric-preview]')).toContainText('第一句');
    await expect(page.locator('[data-lyric-filename]')).toContainText('在线歌曲 - 在线歌手.srt');
    await expect(action('export')).toBeDisabled();
    await action('directory').click();
    await expect(action('export')).toBeEnabled();
    await action('export').click();
    await expect(page.locator('#lyric-result-dialog')).toHaveAttribute('data-result-kind', 'success');
    await page.locator('[data-lyric-result-confirm]').click();
    assert.match(fs.readFileSync(path.join(output, '在线歌曲 - 在线歌手.srt'), 'utf8'), /00:00:01,000 --> 00:00:03,000/);
    await action('export').click(); await page.locator('[data-lyric-result-confirm]').click();
    assert.ok(fs.existsSync(path.join(output, '在线歌曲 - 在线歌手 (1).srt')));
    await page.locator('[data-lyric-reference-source]').selectOption('netease');
    await input.fill('https://y.qq.com/n/ryqq/songDetail/003OUlho2HcRHC'); await input.press('Enter');
    await expect(page.locator('[data-lyric-filename]')).toContainText('QQ 歌曲 - QQ 歌手.srt');
    await expect(page.locator('[data-lyric-selected-source]')).toHaveText('QQ 音乐');
    await input.fill('分享链接 https://163cn.tv/AbCdEf。'); await action('resolve').click();
    await expect(page.locator('[data-lyric-filename]')).toContainText('在线歌曲 - 在线歌手.srt');
    await input.fill('https://example.com/song?id=123'); await action('resolve').click();
    await expect(page.locator('[data-lyric-error]')).not.toBeEmpty();
    await expect(action('export')).toBeDisabled();
    await input.fill('netease:123');
    await app.evaluate(() => { globalThis.referenceSlow = true; });
    await action('resolve').click(); await expect(action('stop')).toBeVisible(); await action('stop').click();
    await expect(page.locator('[data-lyric-notice]')).toContainText('已停止');
    await expect(action('resolve')).toBeEnabled();
    await action('resolve').click(); await action('close').click();
    await app.evaluate(() => { globalThis.referenceSlow = false; });
    await page.locator('.queue-actions [data-action="extract-lyrics"]').click();
    await expect(input).toBeFocused(); await expect(page.locator('[data-lyric-text="original"]')).toBeDisabled();
    await page.locator('[data-lyric-query="title"]').fill('搜索歌曲'); await action('search').click();
    await expect(page.locator('[data-lyric-candidate]')).toHaveCount(1); await page.locator('[data-lyric-candidate="0"]').click();
    await expect(action('export')).toBeEnabled();
    await action('close').click(); await page.locator('[data-action="theme"]').click();
    await page.waitForFunction(() => !document.documentElement.classList.contains('music-theme-revealing'));
    await page.locator('.sidebar [data-action="extract-lyrics"]').click();
    await input.fill('https://music.163.com/#/song?id=123'); await action('resolve').click(); await expect(action('export')).toBeEnabled();
    await page.screenshot({ path: path.join(root, 'artifacts/lyrics-reference-dark.png') });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 740));
    await page.waitForFunction(() => innerWidth <= 1000);
    assert.equal(await page.evaluate(() => document.querySelector('#lyric-ui').scrollWidth > document.querySelector('#lyric-ui').clientWidth + 2), false);
    await page.screenshot({ path: path.join(root, 'artifacts/lyrics-reference-1000.png') });
    // A local track must not override a directly resolved song's duration or missing metadata.
    await action('close').click(); await page.locator('[data-action="demo"]').click();
    await expect(page.locator('.audio-tile')).toHaveCount(8);
    await page.locator('.audio-tile').first().click(); await page.locator('.queue-actions [data-action="extract-lyrics"]').click();
    await expect(page.locator('[data-lyric-candidate]')).toHaveCount(1);
    await input.fill('netease:123'); await action('resolve').click(); await expect(action('export')).toBeEnabled();
    const normalize = value => value.replace(/\r\n/g, '\n');
    const preview = await page.locator('[data-lyric-preview]').textContent();
    assert.match(preview, /00:02:00,000/);
    await action('export').click(); await page.locator('[data-lyric-result-confirm]').click();
    assert.equal(normalize(fs.readFileSync(path.join(output, '在线歌曲 - 在线歌手 (2).srt'), 'utf8')), normalize(preview));
    await app.evaluate(() => { globalThis.referenceMinimal = true; });
    await action('resolve').click(); await expect(action('export')).toBeEnabled();
    await page.locator('.lyric-settings summary').click();
    await page.locator('[data-lyric-name-preset]').selectOption('custom');
    await page.locator('[data-lyric-setting="filenameTemplate"]').fill('{title} - {artist} - {album} - {track}');
    const unknownName = '在线歌曲 - 未知艺术家 - 未知专辑 - 未知序号.srt';
    await expect(page.locator('[data-lyric-filename]')).toHaveText(unknownName);
    await expect(action('export')).toBeEnabled();
    const unknownPreview = await page.locator('[data-lyric-preview]').textContent();
    assert.match(unknownPreview, /00:00:06,000/);
    await action('export').click(); await page.locator('[data-lyric-result-confirm]').click();
    assert.equal(normalize(fs.readFileSync(path.join(output, unknownName), 'utf8')), normalize(unknownPreview));
    assert.deepEqual(errors, []);
    const calls = await app.evaluate(() => globalThis.referenceCalls);
    assert.ok(calls.includes('qq:003OUlho2HcRHC')); assert.ok(calls.includes('netease:123')); assert.ok(!calls.some(url => url.includes('example.com')));
    const result = { passed: true, version: require('../package.json').version, data, output, rendererErrors: errors,
      checks: ['empty library sidebar and toolbar enabled', 'reference input initial focus', 'numeric ID requires platform', 'exact QQ and NetEase IDs fetched', 'metadata filenames and bilingual SRT preview', 'no export without selected directory', 'unknown audio paths and unauthorized directories rejected by IPC', 'online SRT export and numbered collision', 'share redirect', 'bad URL invalidates export', 'cancel/close/reopen discards stale results', 'title search without audio', 'dark theme and 1000px no overflow', 'direct song duration overrides unrelated local duration with byte-matching export preview', 'missing direct song metadata and duration do not fall back to selected local tags'] };
    fs.writeFileSync(path.join(root, 'artifacts/ui-lyric-reference-check.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2));
  } catch (error) { await page.screenshot({ path: path.join(root, 'artifacts/lyric-reference-failure.png') }).catch(() => {}); throw error; }
  finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
